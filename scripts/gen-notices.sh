#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES.md from the modules actually linked into
# the project's packages. Run it after changing dependencies; CI fails if the
# committed file is stale.
set -euo pipefail
cd "$(dirname "$0")/.."
export LC_ALL=C

cat <<'HEADER'
# Third-Party Notices

pki-dash itself is MIT-licensed (see LICENSE). It embeds and redistributes
the following third-party software. Their license terms are reproduced here
as required.

This file is generated by scripts/gen-notices.sh. Do not edit it by hand.
HEADER

go list -deps ./... \
  | xargs go list -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' \
  | sort -u \
  | while read -r path version dir; do
      lic=$(find "$dir" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'COPYING*' -o -iname 'LICENCE*' \) | sort | head -1)
      if [ -z "$lic" ]; then
        echo "ERROR: no license file found for $path" >&2
        exit 1
      fi
      printf '\n---\n\n## %s %s\n\n' "$path" "$version"
      cat "$lic"
    done

# Frontend packages whose code or banner ends up in the shipped bundle: the
# Svelte runtime (and the two small modules it imports) and Tailwind's CSS
# banner. Build-time-only tooling is not redistributed and is not listed.
# Requires `npm ci` in web/.
bundled_npm="svelte clsx esm-env tailwindcss"
for pkg in $bundled_npm; do
  dir="web/node_modules/$pkg"
  if [ ! -d "$dir" ]; then
    echo "ERROR: $dir missing: run 'npm ci' in web/ first" >&2
    exit 1
  fi
  lic=$(find "$dir" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'COPYING*' \) | sort | head -1)
  if [ -z "$lic" ]; then
    echo "ERROR: no license file found for npm package $pkg" >&2
    exit 1
  fi
  version=$(node -p "require('./$dir/package.json').version")
  printf '\n---\n\n## npm: %s %s\n\n' "$pkg" "$version"
  cat "$lic"
done
